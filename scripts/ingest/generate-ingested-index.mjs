#!/usr/bin/env node
/**
 * Regenerate lib/library/ingest/load-manifest.ts from data/ingested/*.json
 * Run after batch ingest: node scripts/ingest/generate-ingested-index.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.join(__dirname, '../..')
const ingestedDir = path.join(repoRoot, 'data/ingested')
const outPath = path.join(repoRoot, 'lib/library/ingest/load-manifest.ts')
const codesPath = path.join(repoRoot, 'lib/library/ingest/ingested-unit-codes.ts')

const files = fs
  .readdirSync(ingestedDir)
  .filter((file) => /^unit-\d+\.\d+\.json$/.test(file))
  .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))

const imports = files.map((file, index) => {
  const unitCode = file.slice('unit-'.length, -'.json'.length)
  const varName = `unit${unitCode.replace('.', '')}`
  return { file, unitCode, varName, index }
})

const lines = [
  ...imports.map(
    ({ file, varName }) =>
      `import ${varName} from '@/data/ingested/${file}' with { type: 'json' }`,
  ),
  "import type { IngestedUnitManifest } from './types'",
  '',
  '/** Auto-generated by scripts/ingest/generate-ingested-index.mjs — do not edit manually. */',
  'const INGESTED_MANIFESTS: Record<string, IngestedUnitManifest> = {',
  ...imports.map(({ unitCode, varName }) => `  '${unitCode}': ${varName} as IngestedUnitManifest,`),
  '}',
  '',
  'export function hasIngestedManifest(unitCode: string): boolean {',
  '  return unitCode in INGESTED_MANIFESTS',
  '}',
  '',
  'export function listIngestedUnitCodes(): string[] {',
  '  return Object.keys(INGESTED_MANIFESTS).sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))',
  '}',
  '',
  'export function loadIngestedManifest(unitCode: string): IngestedUnitManifest | null {',
  '  return INGESTED_MANIFESTS[unitCode] ?? null',
  '}',
  '',
  'export function findIngestedAssessment(',
  '  unitCode: string,',
  '  assessmentId: string,',
  '): IngestedUnitManifest[\'assessments\'][number] | null {',
  '  const manifest = loadIngestedManifest(unitCode)',
  '  if (!manifest) {',
  '    return null',
  '  }',
  '  return manifest.assessments.find((row) => row.id === assessmentId) ?? null',
  '}',
  '',
]

const codeLines = [
  '/**',
  ' * Unit codes that have library ingest data.',
  ' * Safe to import from client components — this file does not load unit JSON.',
  ' * Auto-generated by scripts/ingest/generate-ingested-index.mjs — do not edit manually.',
  ' */',
  'export const INGESTED_UNIT_CODES = [',
  ...imports.map(({ unitCode }) => `  '${unitCode}',`),
  '] as const',
  '',
  'export function listIngestedUnitCodes(): string[] {',
  '  return [...INGESTED_UNIT_CODES]',
  '}',
  '',
]

fs.writeFileSync(outPath, lines.join('\n'))
fs.writeFileSync(codesPath, codeLines.join('\n'))
console.log(`Wrote ${outPath} (${imports.length} units)`)
console.log(`Wrote ${codesPath} (${imports.length} codes)`)
