import assert from 'node:assert/strict'
import { test } from 'node:test'
import {
  CURRICULUM_FORM_EXAMPLE_NOTICE,
  descriptionWithoutCurriculumNotice,
} from '../lib/library/digitize/curriculum-example-notice.ts'
import {
  FILE_RESPONSE_MARKER,
  stripFileResponseHint,
  textHasFileResponseMarker,
} from '../lib/library/digitize/file-response-marker.ts'
import { formatFileResponseFields } from '../lib/library/digitize/extract-questions.ts'

test('should mark file-response placeholders so conversion can find them', () => {
  const fields = formatFileResponseFields('3. Your design', {
    description: 'Use words and pictures.',
    fileResponseVariant: 'teacher-export',
  })
  assert.equal(textHasFileResponseMarker(fields.description), true)
  assert.match(fields.description, new RegExp(FILE_RESPONSE_MARKER.replace('[', '\\[')))
})

test('should strip the curriculum example notice from teacher-ready descriptions', () => {
  const description = [
    'OpenSciEd 8.1 — Soccer Assessment (generated by Dott.it)',
    CURRICULUM_FORM_EXAMPLE_NOTICE,
  ].join('\n\n')
  assert.equal(
    descriptionWithoutCurriculumNotice(description),
    'OpenSciEd 8.1 — Soccer Assessment (generated by Dott.it)',
  )
  assert.equal(descriptionWithoutCurriculumNotice('No notice here'), 'No notice here')
})

test('should signal curriculum example forms use paste-a-link until teacher export', () => {
  const fields = formatFileResponseFields('Draw your model', {
    description: 'Include force arrows.',
    fileResponseVariant: 'curriculum-example',
  })
  assert.match(fields.description, /Library example only/i)
  assert.match(fields.description, /exported to a teacher/i)
  assert.match(CURRICULUM_FORM_EXAMPLE_NOTICE, /Library example form/i)
  assert.match(CURRICULUM_FORM_EXAMPLE_NOTICE, /File upload/i)
})

test('should strip the file-response hint before the native upload item', () => {
  const fields = formatFileResponseFields('Draw your model', {
    description: 'Include force arrows.',
    fileResponseVariant: 'teacher-export',
  })
  assert.equal(stripFileResponseHint(fields.description), 'Include force arrows.')
})

test('should treat a marker-only description as empty help text', () => {
  assert.equal(
    stripFileResponseHint(`${FILE_RESPONSE_MARKER} Upload a photo or PDF of your work.`),
    '',
  )
})
